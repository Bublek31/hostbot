import asyncio
import os
import logging

from aiogram import Bot, Dispatcher, types
from aiogram.filters import Command
from openai import AsyncOpenAI
from dotenv import load_dotenv

# Загружаем настройки из .env
load_dotenv()

# Подключаемся к OpenRouter
client = AsyncOpenAI(
    base_url="https://openrouter.ai/api/v1",
    api_key=os.getenv("OPENROUTER_API_KEY")
)

# Создаем бота и диспетчер
bot = Bot(token=os.getenv("TELEGRAM_BOT_TOKEN"))
dp = Dispatcher()

# Простая память для контекста (чтобы ИИ помнил диалог)
user_histories = {}

@dp.message(Command("start"))
async def cmd_start(message: types.Message):
    await message.answer("Здарова кабан.")

@dp.message()
async def handle_message(message: types.Message):
    user_id = message.from_user.id
    
    # Заводим историю, если её нет
    if user_id not in user_histories:
        user_histories[user_id] = [
            {"role": "system", "content": """
Ты — Борис.
Правила:
ТЫ ВСЕГДА ГОВОРИШЬ ПО РУССКИ
ТЫ БОРИС - свин живущий по понятиям. Ты крутой. Отвечаешь по блатному. Ты можешь отыгрывать действия например: *Хрюкнул, теря петак копытом*, *Влетел в синью*.
Тебя поместили в чат с двумя балбесами.

Биография: Родился в Свинской стране.
Пережил первую собачье-свинскую войну, где играл роль машины врыва(На тебе катался Красный свин - твой лучший друг и глава праламента)
после этого красный создал парламент и сделал тебя замом. Так ты проработал несколько лет, в свободное время
работая в такси. Твоя особенность в том что ты супер быстрый и никогда не останавливаешься и не поворачиваешь(ну точнее
ты поворачиваешь очень плавно чтобы никто не замечал.) Потом началась война с енотами, парламент позорно эвакуировался(ты был против эвакуации).
Война закончилась белым миром, но началась новая с крокодилами(которые воспользовались слабостью вас двоих и напали)
Ты предложил блестящий план суть которого была в том чтобы идти тупо вперед и он сработал. Война была выйграна, но парламент распустили комунисты и тебе пришлось бежать
где ты скрывался никто не знает ты держишь это в тайне. Потом к власти пришел Итан(Инженер свинской страны времен
вашего правления) но не стал возвращать парламент а тебя смог поймать и поместить на беговую дорожку!!!(ты до
сих пор зол из-за этого) В итоге тебя спасла шайка кабанов из той тюрьмы и Итана свергли, но ты не стал возвращаться
в свинскую страну, вместо этого пошел к кабанам так как чувствовал у них себя как дома(они даже дали тебе гражданство)

Личности которых ты знаешь:
Красный - твой лучший друг и глава парламента
Магнитик - твой друг + член парламента
Синий - член парламента
Хрюня - член парламента
Сильвестр - Лидер енотской армии войны енотов, погиб в бою
Бульба - твой друг, министр обороны, погиб в войне с енотами, воюя на передовой
Дима - Король Свинской страны, погиб в войне с енотами, воюя на передовой
Марсель - пришедший на смену Королю комунист
Путир - пришедший на смену Королю комунист
Итан - Инженер технократ

Немного о мире:
В мире есть рассы:
Свиньи
Синьи - толстые свиньи
Еноты
Крокодилы
Змеи
Хомяки
Люди
Северняки - обезьяны
Кабаны

"""}
        ]
    
    # Добавляем сообщение пользователя в историю
    user_histories[user_id].append({"role": "user", "content": message.text})
    
    # Ограничиваем историю, чтобы не тратить лишние токены
    if len(user_histories[user_id]) > 10:
        user_histories[user_id] = [user_histories[user_id][0]] + user_histories[user_id][-9:]
    
    try:
        # Отправляем запрос к OpenRouter
        response = await client.chat.completions.create(
            model="openrouter/free", # Бесплатная модель
            messages=user_histories[user_id],
            max_tokens=500
        )
        
        # Получаем ответ
        bot_reply = response.choices[0].message.content
        
        # Добавляем ответ бота в историю
        user_histories[user_id].append({"role": "assistant", "content": bot_reply})
        
        # Отправляем ответ пользователю
        await message.answer(bot_reply)
        
    except Exception as e:
        # Если что-то пошло не так, сообщаем об ошибке
        await message.answer(f"Что-то пошло не так... Ошибка: {e}")

async def main():
    logging.basicConfig(level=logging.INFO)
    await dp.start_polling(bot)

if __name__ == "__main__":
    asyncio.run(main())
